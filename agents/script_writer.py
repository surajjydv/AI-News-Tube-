def _post_process_script(raw_text: str) -> str:
    """
    Cleans up common LLM artefacts from the generated script:
    - Removes markdown headers, bullets, numbering
    - Removes bracketed labels like [HOOK], **Impact**
    - Removes English section labels (Impact:, Hook:, etc.)
    - Strips emoji that the LLM might still slip in
    - Collapses excess whitespace
    """
    import re
    text = raw_text.strip()

    # Remove markdown-style headers (##, ###, etc.)
    text = re.sub(r'^#{1,6}\s+.*$', '', text, flags=re.MULTILINE)

    # Remove bracketed labels: [HOOK], [MAIN STORY], {HOOK}, etc.
    text = re.sub(r'[\[\{].*?[\]\}]', '', text)

    # Remove bold/italic markdown: **text**, *text*, __text__, _text_
    text = re.sub(r'\*{1,2}(.*?)\*{1,2}', r'\1', text)
    text = re.sub(r'_{1,2}(.*?)_{1,2}', r'\1', text)

    # Remove numbered lines: "1.", "2.", etc. at start of lines
    text = re.sub(r'^\s*\d+[\.\)]\s*', '', text, flags=re.MULTILINE)

    # Remove bullet characters
    text = re.sub(r'^\s*[-â€¢â—�â–¸â–¹â–º]\s*', '', text, flags=re.MULTILINE)

    # Remove English section labels that LLMs love to inject
    # e.g. "Impact:", "Hook:", "Main Story:", "What's Next:", "CTA:", "Sign-off:"
    text = re.sub(
        r'^\s*(Hook|Impact|Analysis|Main\s*Story|What.s\s*Next|CTA|'
        r'Sign[\s-]*off|Opening|Conclusion|Summary|Section)\s*:?\s*$',
        '', text, flags=re.MULTILINE | re.IGNORECASE
    )

    # Remove emoji (broad unicode ranges)
    text = re.sub(
        r'[\U0001F000-\U0001FAFF\u2600-\u27BF\uFE00-\uFE0F'
        r'\U0001F900-\U0001F9FF\U0001FA00-\U0001FA6F'
        r'\U0001FA70-\U0001FAFF\u200D\u2640\u2642]', '', text
    )

    # Remove common artifacts like "---", "===", "â”�â”�â”�", "--"
    text = re.sub(r'[â”€â”�â•�]{2,}', '', text)
    text = re.sub(r'^-{2,}\s*$', '', text, flags=re.MULTILINE)

    # Collapse multiple newlines into paragraph breaks
    text = re.sub(r'\n{3,}', '\n\n', text)

    # Collapse multiple spaces
    text = re.sub(r' {2,}', ' ', text)

    # Strip each line and remove empty lines
    lines = [line.strip() for line in text.split('\n')]
    text = '\n'.join(line for line in lines if line)

    return text.strip()


